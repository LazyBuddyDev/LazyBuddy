// Headless library view fixtures; no accounts or upstream requests.
import assert from 'node:assert/strict';
import {createServer} from 'vite';
import {chromium} from 'playwright-core';
import {mkdir,mkdtemp,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const profiles=fileURLToPath(new URL('../../../tmp/profiles/',import.meta.url));
await mkdir(profiles,{recursive:true});const scratch=await mkdtemp(profiles+'hongguo-views-');
process.env.TEMP=scratch;process.env.TMP=scratch;
const server=await createServer({root,server:{host:'127.0.0.1',port:0}});let browser;
try{
  await server.listen();browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:400,height:600}});
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/news-fixture.html`);
  await page.evaluate(()=>window.showHongguo());
  const tabStyle=()=>page.locator('.tabs button.active').evaluate(button=>({background:getComputedStyle(button).backgroundColor,color:getComputedStyle(button).color,padding:getComputedStyle(button).padding,after:getComputedStyle(button,'::after').content}));
  const initialTabStyle=await tabStyle();
  assert.equal(initialTabStyle.color,'rgb(255, 255, 255)');
  assert.notEqual(initialTabStyle.background,'rgba(0, 0, 0, 0)');
  assert.equal(initialTabStyle.after,'none');
  const search=page.getByRole('toolbar',{name:'搜索工具栏'}),favorites=page.getByRole('toolbar',{name:'收藏工具栏'});
  const reads=()=>page.evaluate(()=>window.hongguoCalls.filter(c=>c.method==='cover.read').length);
  await page.getByRole('textbox',{name:'搜索短剧'}).fill('搜索');
  await search.getByRole('button',{name:'搜索',exact:true}).click();
  await page.getByRole('heading',{name:'搜索样例'}).waitFor();assert.equal(await reads(),0);
  const searchBounds=await search.boundingBox();
  await search.getByRole('button',{name:'切换图标视图'}).click();
  await page.waitForSelector('canvas:not([hidden])');assert.equal(await reads(),1);
  await page.getByRole('button',{name:'收藏搜索样例',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'取消收藏搜索样例',exact:true}).count(),0);
  await search.getByRole('button',{name:'切换列表视图'}).click();
  await search.getByRole('button',{name:'切换图标视图'}).click();
  await page.waitForSelector('canvas:not([hidden])');assert.equal(await reads(),2,'search covers must not enter the favorites memory cache');
  assert.equal(await page.evaluate(()=>window.hongguoCalls.filter(c=>c.method==='search').length),1,'switching views must not repeat the search');
  await page.locator('.tabs').getByRole('button',{name:'收藏',exact:true}).click();
  await page.waitForSelector('.media-result');
  await page.waitForFunction(expected=>{const style=getComputedStyle(document.querySelector('.tabs button.active'));return style.backgroundColor===expected.background&&style.color===expected.color;},initialTabStyle);
  assert.deepEqual(await tabStyle(),initialTabStyle,'both selected tabs must use the shared filled style');
  assert.deepEqual(await favorites.boundingBox(),searchBounds,'toolbar layout must remain stable');
  await favorites.getByRole('button',{name:'切换图标视图'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('canvas:not([hidden])').length===2);
  assert.equal(await reads(),4);
  await page.getByRole('button',{name:'取消收藏春日',exact:true}).waitFor();
  await favorites.getByRole('button',{name:'切换列表视图'}).click();
  await favorites.getByRole('button',{name:'切换图标视图'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('canvas:not([hidden])').length===2);
  assert.equal(await reads(),4,'favorites must retain their cover cache');
  assert.ok(await page.evaluate(()=>window.hongguoCalls.some(c=>c.method==='progress.sync')),'entry must synchronize cloud history');
  await page.evaluate(()=>window.setHongguoVisible(false));
  await page.waitForFunction(()=>!document.querySelector('.media-library'));
  await page.evaluate(()=>{
    window.progressState={state:'signed_in',name:'样例账号',operation:'pending'};
    window.originalObserver=window.IntersectionObserver;
    window.IntersectionObserver=class {observe(){} disconnect(){}};
    window.setHongguoVisible(true);
  });
  await page.waitForFunction(()=>document.querySelectorAll('canvas:not([hidden])').length===2);
  assert.equal(await page.getByText('暂无封面',{exact:true}).count(),0);
  assert.equal(await reads(),4,'returning from another page must paint cached covers without loading');
  await page.waitForFunction(()=>window.hongguoCalls.some(c=>c.method==='account.status'));
  await page.evaluate(()=>window.progressState={state:'signed_in',name:'样例账号',operation:null,history:{'1':{episode:7,time:12}}});
  await page.getByText('看到第 7 集 · 共 10 集',{exact:true}).waitFor();
  await page.evaluate(()=>{window.IntersectionObserver=window.originalObserver;delete window.progressState;});
  await page.locator('.tabs').getByRole('button',{name:'搜索',exact:true}).click();
  await page.waitForSelector('canvas:not([hidden])');
  assert.equal(await page.getByRole('textbox',{name:'搜索短剧'}).inputValue(),'搜索');
  assert.equal(await page.evaluate(()=>localStorage.getItem('lazybuddy.hongguo.searchView')),'grid');
  assert.equal(await page.evaluate(()=>localStorage.getItem('lazybuddy.hongguo.favoritesView')),'grid');
  assert.equal(await page.locator('.favorite-tile').count(),1);
  await page.evaluate(async()=>{window.failCover=true;await window.showHongguo();});
  await page.locator('.tabs').getByRole('button',{name:'收藏',exact:true}).click();
  await page.waitForFunction(()=>window.hongguoCalls.filter(c=>c.method==='cover.read').length===2);
  assert.equal(await page.locator('canvas:not([hidden])').count(),0);
  await page.evaluate(()=>window.failCover=false);
  await favorites.getByRole('button',{name:'刷新收藏'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('canvas:not([hidden])').length===2);
  await page.evaluate(async()=>{window.holdFavorites=true;window.favoritesState={state:'signed_in',name:'样例账号',operation:'pending'};await window.showHongguo();});
  await page.locator('.tabs').getByRole('button',{name:'收藏',exact:true}).click();
  await page.getByText('正在获取收藏…',{exact:true}).waitFor({timeout:3000});
  assert.equal(await page.getByText('暂无收藏',{exact:true}).count(),0);
  assert.equal(await page.getByText('没有匹配的收藏',{exact:true}).count(),0);
  await page.evaluate(()=>{window.holdFavorites=false;window.releaseFavorites();});
  await page.waitForFunction(()=>window.hongguoCalls.some(c=>c.method==='account.status'));
  assert.equal(await page.getByText('正在获取收藏…',{exact:true}).count(),1);
  await page.evaluate(()=>window.favoritesState={state:'signed_in',name:'样例账号',operation:null,favorites:[]});
  await page.getByText('暂无收藏',{exact:true}).waitFor();
  await page.evaluate(()=>window.favoritesState={state:'signed_in',name:'样例账号',operation:null,favorites_error:'favorites_unavailable'});
  await favorites.getByRole('button',{name:'刷新收藏'}).click();
  await page.getByText('收藏列表读取失败',{exact:true}).waitFor();
  assert.equal(await page.getByText('暂无收藏',{exact:true}).count(),0);
  await page.evaluate(()=>{window.holdFavorites=true;window.favoritesState={state:'signed_in',name:'样例账号',operation:'pending'};});
  await favorites.getByRole('button',{name:'刷新收藏'}).click();
  await page.getByText('正在获取收藏…',{exact:true}).waitFor();
  assert.equal(await page.getByText('暂无收藏',{exact:true}).count(),0);
  await page.evaluate(()=>{window.holdFavorites=false;window.favoritesState={state:'signed_in',name:'样例账号',operation:null,favorites:[{id:'3',title:'加载完成样例',episodes:10}]};window.releaseFavorites();});
  await page.getByText('加载完成样例',{exact:true}).waitFor();
  await page.getByRole('textbox',{name:'筛选收藏'}).fill('不存在的名称');
  await page.getByText('没有匹配的收藏',{exact:true}).waitFor();
  console.log('Shared views, cache recovery and delayed/pending/empty/filtered favorites states passed.');
}finally{await browser?.close();await server.close();await rm(scratch,{recursive:true,force:true});}
