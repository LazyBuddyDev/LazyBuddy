// Headless feature notice fixtures; no accounts or upstream requests.
import assert from 'node:assert/strict';
import {createServer} from 'vite';
import {chromium} from 'playwright-core';
import {mkdir,mkdtemp,rm,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=fileURLToPath(new URL('../../../tmp/verification-news-design/',import.meta.url));
const profiles=fileURLToPath(new URL('../../../tmp/profiles/',import.meta.url));
await mkdir(profiles,{recursive:true});const scratch=await mkdtemp(profiles+'news-design-');
process.env.TEMP=scratch;process.env.TMP=scratch;
const server=await createServer({root,server:{host:'127.0.0.1',port:0}});let browser;
try{
  await server.listen();browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:600,height:760}});
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/notice-fixture.html`);
  await page.waitForSelector('[data-events-ready=true]');
  await page.evaluate(()=>window.designSources=[{id:'weibo-hot-search',name:'微博热搜'},{id:'zhihu-hot-search',name:'知乎热榜'},{id:'bilibili-hot-search',name:'哔哩哔哩',subtitle:'热门'},{id:'baidu',name:'百度热搜'}]);
  await page.getByLabel('选择功能').selectOption('news');
  await page.waitForFunction(()=>document.querySelectorAll('.source-logo').length===4&&Array.from(document.querySelectorAll('.source-logo')).every(i=>i.complete&&i.naturalWidth>0));
  const styles=await page.locator('.source-heading').evaluateAll(nodes=>nodes.map(n=>({bg:getComputedStyle(n).backgroundColor,border:getComputedStyle(n).borderLeftColor,height:n.getBoundingClientRect().height})));
  assert.equal(new Set(styles.map(s=>s.border)).size,4);assert.equal(new Set(styles.map(s=>s.bg)).size,4);
  assert.ok(styles.every(s=>s.height>=43));
  assert.match(await page.locator('.source-heading h2').nth(2).textContent(),/哔哩哔哩 · 热门/);
  assert.equal(new Set(await page.locator('.source-card').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).backgroundColor))).size,1);
  assert.ok((await page.locator('.toolbar').evaluate(n=>getComputedStyle(n).backgroundColor)).includes('21, 63, 50'));
  await page.getByRole('button',{name:'置顶',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="置顶"]').getAttribute('aria-pressed')==='true');
  await mkdir(output,{recursive:true});
  await page.screenshot({path:output+'news-light.png'});
  await page.getByRole('button',{name:'功能',exact:true}).click();await page.getByRole('heading',{name:'可用功能'}).waitFor();
  await page.getByRole('button',{name:'功能',exact:true}).click();
  await page.locator('.toolbar').getByRole('button',{name:'设置',exact:true}).click();
  await page.getByRole('button',{name:'显示设置',exact:true}).click();
  await page.getByRole('switch',{name:'深色模式',exact:true}).click();
  await page.getByRole('button',{name:'返回页面',exact:true}).click();
  await page.waitForSelector('.app-shell.dark .source-card');
  await page.screenshot({path:output+'news-dark.png'});
  await page.setViewportSize({width:400,height:700});
  assert.ok(await page.locator('.toolbar').evaluate(n=>n.scrollWidth<=n.clientWidth));
  assert.ok(await page.locator('.page').evaluate(n=>n.scrollWidth<=n.clientWidth));
  await page.screenshot({path:output+'news-narrow.png'});
  const platforms=(await readdir(new URL('../../../assets/source-icons/',import.meta.url))).filter(name=>/\.(png|ico)$/.test(name)).map(name=>name.replace(/\.(png|ico)$/,''));
  await page.reload();await page.waitForSelector('[data-events-ready=true]');
  await page.evaluate(names=>window.designSources=names.map(id=>({id,name:id})),platforms);
  await page.getByLabel('选择功能').selectOption('news');
  await page.waitForFunction(count=>document.querySelectorAll('.source-logo').length===count&&Array.from(document.querySelectorAll('.source-logo')).every(i=>i.complete&&i.naturalWidth>0),platforms.length);
  assert.equal(platforms.length,45);
  console.log('45 source icons, platform colors, toolbar actions, pin selection and dark/narrow layouts passed.');
}finally{await browser?.close();await server.close();await rm(scratch,{recursive:true,force:true});}
